    public void put(Indicator indicator, String... ids) {
        for (String id : ids) {
            byId.put(normalize(id), indicator);
        }
    }

    public void remove(String id) { byId.remove(normalize(id)); }

    /** Suffix (or, ending in '_', prefix) rules for whole block families. Exact ids always win. */
    public void putSuffix(Indicator indicator, String... suffixes) {
        for (String s : suffixes) bySuffix.put(s, indicator);
    }

    public Indicator lookup(String id) {
        String n = normalize(id);
        Indicator exact = byId.get(n);
        if (exact != null || !n.startsWith("minecraft:")) return exact;
        String path = n.substring("minecraft:".length());
        for (Map.Entry<String, Indicator> e : bySuffix.entrySet()) {
            String k = e.getKey();
            boolean prefix = k.endsWith("_") && !k.startsWith("_");
            if (prefix ? path.startsWith(k) : path.endsWith(k)) return e.getValue();
        }
        return null;
    }

    public Map<String, Indicator> asMap() { return Collections.unmodifiableMap(byId); }

    public static String normalize(String id) {
        return id.indexOf(':') >= 0 ? id : "minecraft:" + id;
    }
